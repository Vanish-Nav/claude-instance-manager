test('a restore selection keeps only the chosen projects and can leave Cowork tasks out', async t => {
  const f = await fixture(t)
  await f.put(path.join('local-agent-mode-sessions', 'task-1', 'state.json'), '{}')
  const item = path.join(f.root, 'backup-session')
  await backup.copyTier(f.profile, item, { tier: 'session', claudeProjectsRoot: f.projects })
  const target = path.join(f.root, 'target')
  const projectsRoot = path.join(f.root, 'projects-restore')
  const present = path.join(f.root, 'present-project')
  await backup.restoreTier(item, target, { tier: 'session', claudeProjectsRoot: projectsRoot, selection: { projects: [present.toUpperCase()], cowork: false } })
  const remaining = await backup.sessionProjects(target)
  assert.deepEqual(remaining.map(project => project.cwd), [present])
  assert.equal(await exists(path.join(target, 'local-agent-mode-sessions')), false)
  assert.equal(await exists(path.join(projectsRoot, 'D--Work-Repo')), false, 'transcripts of a dropped project are not restored')
  await backup.restoreTier(item, path.join(f.root, 'target-all'), { tier: 'session', claudeProjectsRoot: projectsRoot, selection: { projects: null, cowork: true } })
  assert.equal((await backup.sessionProjects(path.join(f.root, 'target-all'))).length, 2)
  assert.equal(await exists(path.join(f.root, 'target-all', 'local-agent-mode-sessions')), true)
  assert.equal(await exists(path.join(projectsRoot, 'D--Work-Repo', 'session.jsonl')), true)
})
