test('restoring a session tier replaces only session entries and keeps caches', async t => {
  const f = await fixture(t)
  const item = path.join(f.root, 'backup-session')
  await backup.copyTier(f.profile, item, { tier: 'session', claudeProjectsRoot: f.projects })
  const target = path.join(f.root, 'target')
  await f.put('Preferences', 'old', target)
  await f.put(path.join('Cache', 'keep'), 'keep', target)
  await f.put(path.join('Network', 'Cookies'), 'old-cookies', target)
  await f.put(path.join('Network', 'Stale'), 'stale', target)
  const projectsRoot = path.join(f.root, 'projects-restore')
  await backup.restoreTier(item, target, { tier: 'session', claudeProjectsRoot: projectsRoot })
  assert.equal(await readFile(path.join(target, 'Preferences'), 'utf8'), '{}')
  assert.equal(await readFile(path.join(target, 'Network', 'Cookies'), 'utf8'), 'cookies')
  assert.equal(await exists(path.join(target, 'Network', 'Stale')), false)
  assert.equal(await exists(path.join(target, 'Cache', 'keep')), true)
  assert.equal(await exists(path.join(target, backup.projectsFolderName)), false)
  assert.equal(await readFile(path.join(projectsRoot, 'D--Work-Repo', 'session.jsonl'), 'utf8'), 'transcript')
})

test('restoring a settings export keeps the target login keys and login files', async t => {
  const f = await fixture(t)
  const item = path.join(f.root, 'export')
  await backup.copyTier(f.profile, item, { tier: 'settings', claudeProjectsRoot: f.projects })
  const target = path.join(f.root, 'target')
  await f.put('config.json', JSON.stringify({ locale: 'ru', 'oauth:tokenCache': 'mine' }), target)
  await f.put('Local State', 'my-key', target)
  await f.put('ant-did', 'my-device', target)
  await backup.restoreTier(item, target, { tier: 'settings', claudeProjectsRoot: f.projects })
  const config = JSON.parse(await readFile(path.join(target, 'config.json'), 'utf8'))
  assert.equal(config.locale, 'en')
  assert.equal(config['oauth:tokenCache'], 'mine')
  assert.equal(await readFile(path.join(target, 'Local State'), 'utf8'), 'my-key')
  assert.equal(await readFile(path.join(target, 'ant-did'), 'utf8'), 'my-device')
})

test('a full restore replaces the folder and reports Code sessions whose project is gone', async t => {
  const f = await fixture(t)
  const item = path.join(f.root, 'backup-full')
  await backup.copyTier(f.profile, item, { tier: 'full', claudeProjectsRoot: f.projects })
  const target = path.join(f.root, 'target')
  await f.put('leftover', 'x', target)
  await backup.restoreTier(item, target, { tier: 'full', claudeProjectsRoot: f.projects })
  assert.equal(await exists(path.join(target, 'leftover')), false)
  const missing = await backup.missingProjects(target)
  assert.deepEqual(missing, [{ cwd: 'D:\\Work\\Repo', title: 'First' }])
})

test('restored transcripts never overwrite newer local files', async t => {
  const f = await fixture(t)
  const item = path.join(f.root, 'backup-session')
  await backup.copyTier(f.profile, item, { tier: 'session', claudeProjectsRoot: f.projects })
  await writeFile(path.join(f.projects, 'D--Work-Repo', 'session.jsonl'), 'newer')
  await backup.restoreProjects(item, f.projects)
  assert.equal(await readFile(path.join(f.projects, 'D--Work-Repo', 'session.jsonl'), 'utf8'), 'newer')
})

test('profile sizes group entries by category and count referenced transcripts', async t => {
  const f = await fixture(t)
  const sizes = await backup.profileSizes(f.profile, f.projects)
  const byName = Object.fromEntries(sizes.entries.map(entry => [entry.name, entry]))
  assert.equal(byName.Cache.category, 'cache')
  assert.equal(byName.Network.category, 'session')
  assert.equal(byName.Partitions.category, 'data')
  assert.equal(sizes.projectsBytes, 'transcript'.length)
  assert.equal(sizes.cacheBytes, 'cache-bytes-1234'.length + 'bundle'.length + 'log'.length)
  assert.ok(sizes.fullBytes > sizes.sessionBytes)
  assert.ok(sizes.sessionBytes >= sizes.projectsBytes)
})

test('device ids are base64 UUIDs and never repeat', () => {
  const first = backup.newDeviceId()
  const second = backup.newDeviceId()
  assert.match(Buffer.from(first, 'base64').toString('utf8'), /^[0-9a-f-]{36}$/)
  assert.notEqual(first, second)
})

